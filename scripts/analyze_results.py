def figures(data):
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    import numpy as np

    FIG.mkdir(parents=True, exist_ok=True)
    plt.rcParams.update({"font.size": 9, "axes.spines.top": False, "axes.spines.right": False,
                         "axes.grid": True, "grid.alpha": 0.25, "figure.dpi": 150})
    colors = ["#4C78A8", "#F58518", "#54A24B", "#B279A2", "#E45756"]
    note = "Virtual simulation time, 30 seeds per configuration (box = IQR, line = median, dots = runs)"

    def values(recs, metric):
        return [r[metric] for r in recs if r["status"] == "ok" and r.get(metric) is not None]

    def box(ax, series, labels, metric_title, ylabel=None, logy=False):
        pos = list(range(1, len(series) + 1))
        usable = [(p, s) for p, s in zip(pos, series) if s]
        if usable:
            bp = ax.boxplot([s for _, s in usable], positions=[p for p, _ in usable], widths=0.55,
                            showfliers=False, patch_artist=True, medianprops={"color": "black"})
            for patch, (p, _) in zip(bp["boxes"], usable):
                patch.set_facecolor(colors[(p - 1) % len(colors)])
                patch.set_alpha(0.55)
            rng = np.random.default_rng(0)
            for p, s in usable:
                ax.scatter(p + rng.uniform(-0.17, 0.17, len(s)), s, s=7, color="#333", alpha=0.55, zorder=3)
        ax.set_xticks(pos)
        ax.set_xticklabels([f"{l}\n(n={len(s)})" for l, s in zip(labels, series)])
        ax.set_title(metric_title, fontsize=9.5)
        if ylabel:
            ax.set_ylabel(ylabel)
        if logy:
            ax.set_yscale("log")

    def save(fig, name):
        fig.text(0.5, 0.005, note, ha="center", fontsize=7.5, color="#555")
        fig.tight_layout(rect=(0, 0.03, 1, 1))
        fig.savefig(FIG / name, dpi=150)
        plt.close(fig)

    # Figure 1 - baseline
    recs = groups(data["exp-01"]["records"])
    ns = [n for (n, _) in recs]
    labels = [f"{n} nodes" for n in ns]
    interval = data["exp-01"]["scenario"]["workload"]["interval_ms"]
    fig, axs = plt.subplots(1, 3, figsize=(11, 3.8))
    box(axs[0], [values(r, "election_latency_ms") for r in recs.values()], labels, "Election latency", "ms (virtual)")
    box(axs[1], [values(r, "commit_latency_ms_p50") for r in recs.values()], labels, "Commit latency (per-run P50)", "ms (virtual)")
    box(axs[2], [values(r, "throughput_commands_per_second") for r in recs.values()], labels, "Throughput", "commands / s (virtual)")
    axs[2].axhline(1000 / interval, ls="--", color="#c0392b", lw=1)
    axs[2].text(0.98, 0.12, f"dashed line: offered load = {1000 / interval:.0f} cmd/s", transform=axs[2].transAxes, color="#c0392b", fontsize=7.5, ha="right")
    fig.suptitle("Figure 1 - EXP-01 baseline (no faults)", fontsize=11)
    save(fig, "fig1-baseline-performance.png")

    # Figure 2 - leader crash
    r2 = groups(data["exp-02"]["records"])
    r1 = groups(data["exp-01"]["records"])
    ns2 = [n for (n, _) in r2]
    labels2 = [f"{n} nodes" for n in ns2]
    fig, axs = plt.subplots(1, 3, figsize=(11, 3.8))
    box(axs[0], [values(r, "reelection_latency_ms") for r in r2.values()], labels2, "Re-election latency after leader crash", "ms (virtual)")
    x = np.arange(len(ns2))
    med_init = [statistics.median(values(r, "election_latency_ms")) for r in r2.values()]
    med_re = [statistics.median(values(r, "reelection_latency_ms")) for r in r2.values()]
    axs[1].bar(x - 0.18, med_init, 0.36, label="initial election", color=colors[0], alpha=0.8)
    axs[1].bar(x + 0.18, med_re, 0.36, label="re-election after crash", color=colors[1], alpha=0.8)
    axs[1].set_xticks(x)
    axs[1].set_xticklabels(labels2)
    axs[1].set_title("Median election vs re-election latency", fontsize=9.5)
    axs[1].set_ylabel("ms (virtual)")
    axs[1].legend(fontsize=7.5, frameon=False)
    box(axs[2], [values(r, "failed_elections") for r in r2.values()], labels2, "Failed elections per run", "count")
    fig.suptitle("Figure 2 - EXP-02 leader crash at 3000 ms (leader never restarts)", fontsize=11)
    save(fig, "fig2-leader-crash-recovery.png")

    # Figure 3 - partitions
    a, b = groups(data["exp-03"]["records"]), groups(data["exp-03b"]["records"])
    ra, rb = next(iter(a.values())), next(iter(b.values()))
    lab = ["3/2 split\n(leader in minority)", "2/2/1 split\n(no quorum)"]
    fig, axs = plt.subplots(1, 3, figsize=(11, 3.9))
    box(axs[0], [values(ra, "commands_committed"), values(rb, "commands_committed")], lab, "Commands committed (of 100 submitted)", "commands")
    box(axs[1], [values(ra, "reelection_latency_ms"), values(rb, "reelection_latency_ms")], lab, "Time to first leader election after partition", "ms (virtual, log scale)", logy=True)
    box(axs[2], [values(ra, "failed_elections"), values(rb, "failed_elections")], lab, "Failed elections per run", "count")
    fig.suptitle("Figure 3 - EXP-03 / EXP-03B partition at 3000 ms, healed at 7000 ms (5 nodes)", fontsize=11)
    save(fig, "fig3-partition-behaviour.png")

    # Figure 4 - degradation
    r4 = groups(data["exp-04"]["records"])
    names = [v for (_, v) in r4]
    short = [n.replace("delay", "d").replace("-loss", "\nloss ") + "%" for n in names]
    fig, axs = plt.subplots(2, 3, figsize=(12, 6.6))
    panels = [("election_latency_ms", "Election latency", "ms (virtual)"),
              ("commit_latency_ms_p50", "Commit latency (per-run P50)", "ms (virtual)"),
              ("commit_latency_ms_p95", "Commit latency (per-run P95)", "ms (virtual)"),
              ("throughput_commands_per_second", "Throughput", "commands / s (virtual)"),
              ("failed_elections", "Failed elections per run", "count"),
              ("message_delivery_rate", "Message delivery rate", "delivered / sent")]
    for ax, (m, title, yl) in zip(axs.flat, panels):
        box(ax, [values(r, m) for r in r4.values()], short, title, yl)
        ax.tick_params(axis="x", labelsize=7)
    fig.suptitle("Figure 4 - EXP-04 network degradation (5 nodes; dX = base delay ms, loss = message loss probability)", fontsize=11)
    save(fig, "fig4-network-degradation.png")

    # Figure 5 - restart recovery
    r5 = groups(data["exp-05"]["records"])
    ns5 = [n for (n, _) in r5]
    labels5 = [f"{n} nodes" for n in ns5]
    fig, axs = plt.subplots(1, 3, figsize=(11, 3.8))
    box(axs[0], [values(r, "recovery_time_ms") for r in r5.values()], labels5, "recovery_time_ms (see workload caveat)", "ms (virtual)")
    measured = [len(values(r, "reelection_latency_ms")) for r in r5.values()]
    totals = [len(r) for r in r5.values()]
    axs[1].bar(range(len(ns5)), measured, color=colors[2], alpha=0.8)
    for i, (m, t) in enumerate(zip(measured, totals)):
        axs[1].text(i, m + 0.3, f"{m}/{t}", ha="center", fontsize=8)
    axs[1].set_xticks(range(len(ns5)))
    axs[1].set_xticklabels(labels5)
    axs[1].set_ylim(0, max(totals) * 0.6)
    axs[1].set_title("Runs with a leader election after the crash", fontsize=9.5)
    axs[1].set_ylabel("runs")
    box(axs[2], [values(r, "reelection_latency_ms") for r in r5.values()], labels5, "Re-election latency (those runs only)", "ms (virtual)")
    fig.suptitle("Figure 5 - EXP-05 node-3 crashes at 3000 ms and restarts at 7000 ms", fontsize=11)
    save(fig, "fig5-restart-recovery.png")

    # Figure 6 - supplementary: why recovery_time_ms is not an intrinsic recovery duration
    fig, ax = plt.subplots(figsize=(7.5, 3.8))
    series, labs = [], []
    for key in ("exp-02", "exp-05", "exp-03", "exp-03b"):
        e = data[key]
        rem, end = removal_ms(e["scenario"]), workload_end_ms(e["scenario"])
        series.append([rem + r["recovery_time_ms"] - end for r in e["records"] if r.get("recovery_time_ms") is not None])
        labs.append(e["id"])
    box(ax, series, labs, "Instant the cluster was first 'stable' minus time of the last client command",
        "ms (virtual); negative = stable before the workload ended")
    ax.axhline(0, color="#c0392b", lw=1, ls="--")
    fig.suptitle("Figure 6 (supplementary) - recovery_time_ms versus the workload schedule", fontsize=11)
    save(fig, "fig6-recovery-metric-check.png")


def main():
    data = load()
    text, problems = verify(data)
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "data-verification.md").write_text(text, encoding="utf-8")
    write_tables(data)
    try:
        figures(data)
    except ImportError:
        print("matplotlib/numpy not installed: tables written, figures skipped")
    print(text)
    return 1 if problems else 0


if __name__ == "__main__":
    raise SystemExit(main())
