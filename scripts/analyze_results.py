#!/usr/bin/env python3
"""Verify, summarise and plot the experiment results in results/runs/.

Inputs  : results/runs/<exp>/{runs.jsonl, summary.csv, scenario.json}
Outputs : results/analysis/experiment-overview.csv
          results/analysis/metrics-comparison.csv
          results/analysis/workload-artifact-check.csv
          results/analysis/data-verification.md
          results/analysis/figures/*.png

Everything is computed from the files above; nothing is typed in by hand.
Requires Python 3.9+ and matplotlib/numpy (only for the figures).
Usage: python scripts/analyze_results.py
"""
import csv
import json
import math
import statistics
from collections import OrderedDict, defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RUNS = ROOT / "results" / "runs"
OUT = ROOT / "results" / "analysis"
FIG = OUT / "figures"

EXPS = [
    ("exp-01", "EXP-01", "Baseline"),
    ("exp-02", "EXP-02", "Leader crash"),
    ("exp-03", "EXP-03", "Network partition (3/2, leader in minority)"),
    ("exp-03b", "EXP-03B", "No quorum (2/2/1)"),
    ("exp-04", "EXP-04", "Network degradation"),
    ("exp-05", "EXP-05", "Restart recovery"),
]
METRICS = [
    "election_latency_ms",
    "reelection_latency_ms",
    "commit_latency_ms_p50",
    "throughput_commands_per_second",
    "recovery_time_ms",
    "message_delivery_rate",
    "failed_elections",
]
T95 = [12.706, 4.303, 3.182, 2.776, 2.571, 2.447, 2.365, 2.306, 2.262, 2.228,
       2.201, 2.179, 2.160, 2.145, 2.131, 2.120, 2.110, 2.101, 2.093, 2.086,
       2.080, 2.074, 2.069, 2.064, 2.060, 2.056, 2.052, 2.048, 2.045, 2.042]


def percentile(sorted_vals, p):
    """Linear interpolation, identical to internal/observability.Percentile."""
    if len(sorted_vals) == 1:
        return sorted_vals[0]
    rank = p / 100 * (len(sorted_vals) - 1)
    lo, hi = math.floor(rank), math.ceil(rank)
    if lo == hi:
        return sorted_vals[lo]
    frac = rank - lo
    return sorted_vals[lo] * (1 - frac) + sorted_vals[hi] * frac


def summarize(values):
    """Same statistics and thresholds as internal/observability.Summarize."""
    if not values:
        return None
    s = sorted(values)
    n = len(s)
    mean = sum(s) / n
    out = {"n": n, "mean": mean, "median": percentile(s, 50), "min": s[0], "max": s[-1],
           "std_dev": 0.0, "p95": None, "p99": None, "ci95_half": None}
    if n >= 2:
        sd = math.sqrt(sum((v - mean) ** 2 for v in s) / (n - 1))
        out["std_dev"] = sd
        t = T95[n - 2] if n - 1 <= len(T95) else 1.96
        out["ci95_half"] = t * sd / math.sqrt(n)
    if n >= 20:
        out["p95"] = percentile(s, 95)
    if n >= 100:
        out["p99"] = percentile(s, 99)
    return out


def load():
    data = OrderedDict()
    for key, exp_id, title in EXPS:
        d = RUNS / key
        records = [json.loads(line) for line in (d / "runs.jsonl").read_text(encoding="utf-8").splitlines() if line.strip()]
        scenario = json.loads((d / "scenario.json").read_text(encoding="utf-8"))
        with open(d / "summary.csv", newline="", encoding="utf-8") as fh:
            summary = list(csv.DictReader(fh))
        data[key] = {"id": exp_id, "title": title, "records": records, "scenario": scenario, "summary": summary}
    return data


def groups(records):
    g = OrderedDict()
    for r in records:
        g.setdefault((r["node_count"], r["variant"]), []).append(r)
    return g


def fmt(v, digits=4):
    return "" if v is None else f"{v:.{digits}g}"


def workload_end_ms(sc):
    w = sc["workload"]
    return w["start_ms"] + (w["commands"] - 1) * w["interval_ms"] if w["commands"] else None


def removal_ms(sc):
    """Fault removal time used by the runner for recovery_time_ms (None when undefined)."""
    removal, crash = None, None
    for f in sc.get("faults", []) or []:
        t = f["at_ms"]
        if f["type"] in ("crash", "crash_leader"):
            crash = t if crash is None else max(crash, t)
            if f.get("restart_after_ms", 0) > 0:
                removal = t + f["restart_after_ms"] if removal is None else max(removal, t + f["restart_after_ms"])
        elif f["type"] in ("restart", "heal"):
            removal = t if removal is None else max(removal, t)
    return removal if removal is not None else crash


def verify(data):
    lines = ["# Data verification", "",
             "Generated by `scripts/analyze_results.py`. Every check recomputes a number from `runs.jsonl` / `scenario.json` and compares it with the file written by the experiment runner.", ""]
    problems = 0
    lines += ["## Run accounting", "",
              "| Experiment | Configured runs | Records | status ok | status error | Unique (nodes, variant, seed) | Safety violations | Distinct trace hashes | code_version |",
              "|---|---:|---:|---:|---:|---:|---:|---:|---|"]
    total_cfg = total_ok = total_viol = 0
    for key, e in data.items():
        sc, recs = e["scenario"], e["records"]
        variants = max(1, len(sc.get("variants") or []))
        configured = len(sc["node_counts"]) * variants * sc["seeds"]
        ok = sum(r["status"] == "ok" for r in recs)
        err = len(recs) - ok
        uniq = len({(r["node_count"], r["variant"], r["seed"]) for r in recs})
        viol = sum(r["safety_violations"] for r in recs)
        hashes = len({r["trace_hash"] for r in recs})
        versions = ",".join(sorted({r["code_version"] for r in recs}))
        if configured != len(recs) or uniq != len(recs) or err:
            problems += 1
        total_cfg += configured
        total_ok += ok
        total_viol += viol
        lines.append(f"| {e['id']} | {configured} | {len(recs)} | {ok} | {err} | {uniq} | {viol} | {hashes} | {versions} |")
    lines.append(f"| **Total** | **{total_cfg}** | **{sum(len(e['records']) for e in data.values())}** | **{total_ok}** | | | **{total_viol}** | | |")

    lines += ["", "## summary.csv versus recomputation from runs.jsonl", "",
              "Statistics (n, mean, std dev, median, min, max, P95, P99, 95% CI half-width) are recomputed with the same formulas as the Go code; relative tolerance 1e-6.", ""]
    checked = mismatches = 0
    details = []
    for key, e in data.items():
        by_key = {(int(r["node_count"]), r["variant"], r["metric"]): r for r in e["summary"]}
        for (n, variant), recs in groups(e["records"]).items():
            for m in METRICS:
                vals = [float(r[m]) for r in recs if r["status"] == "ok" and r.get(m) is not None]
                row = by_key.get((n, variant, m))
                if row is None:
                    mismatches += 1
                    details.append(f"{e['id']} n={n} {variant} {m}: missing from summary.csv")
                    continue
                s = summarize(vals)
                if int(row["measured"]) != len(vals) or int(row["runs"]) != len(recs):
                    mismatches += 1
                    details.append(f"{e['id']} n={n} {variant} {m}: measured/runs differ")
                    continue
                if s is None:
                    if row["mean"] != "":
                        mismatches += 1
                        details.append(f"{e['id']} n={n} {variant} {m}: expected empty statistics")
                    checked += 1
                    continue
                for field in ("mean", "std_dev", "median", "min", "max", "p95", "p99", "ci95_half"):
                    want, got = s[field], row[field]
                    checked += 1
                    if want is None:
                        ok_field = got == ""
                    else:
                        ok_field = got != "" and math.isclose(float(got), want, rel_tol=1e-6, abs_tol=1e-9)
                    if not ok_field:
                        mismatches += 1
                        details.append(f"{e['id']} n={n} {variant} {m}.{field}: csv={got!r} recomputed={want!r}")
    problems += mismatches
    lines.append(f"- Values compared: **{checked}**; mismatches: **{mismatches}**.")
    lines += [f"- {d}" for d in details[:50]]
    lines += ["", f"## Result", "", "All checks passed." if problems == 0 else f"**{problems} problem(s) found - see above.**", ""]
    return "\n".join(lines), problems


def write_tables(data):
    OUT.mkdir(parents=True, exist_ok=True)
    with open(OUT / "experiment-overview.csv", "w", newline="", encoding="utf-8") as fh:
        w = csv.writer(fh)
        w.writerow(["experiment_id", "name", "node_counts", "variants", "seeds_per_configuration", "configured_runs",
                    "completed_runs", "error_runs", "safety_violations", "duration_virtual_ms", "fault_schedule",
                    "workload_commands", "workload_interval_ms"])
        for e in data.values():
            sc, recs = e["scenario"], e["records"]
            variants = [v["name"] for v in sc.get("variants") or []] or ["default"]
            faults = "; ".join(f"{f['type']}@{f['at_ms']}ms" for f in sc.get("faults") or []) or "none"
            w.writerow([e["id"], e["title"], " ".join(map(str, sc["node_counts"])), " ".join(variants), sc["seeds"],
                        len(sc["node_counts"]) * len(variants) * sc["seeds"], sum(r["status"] == "ok" for r in recs),
                        sum(r["status"] != "ok" for r in recs), sum(r["safety_violations"] for r in recs),
                        sc["duration_ms"], faults, sc["workload"]["commands"], sc["workload"]["interval_ms"]])

    cols = ["experiment_id", "node_count", "variant", "metric", "source", "runs", "measured", "mean", "std_dev",
            "median", "min", "max", "p95", "p99", "ci95_half"]
    with open(OUT / "metrics-comparison.csv", "w", newline="", encoding="utf-8") as fh:
        w = csv.writer(fh)
        w.writerow(cols)
        for e in data.values():
            for row in e["summary"]:
                w.writerow([e["id"], row["node_count"], row["variant"], row["metric"], "summary.csv", row["runs"],
                            row["measured"], row["mean"], row["std_dev"], row["median"], row["min"], row["max"],
                            row["p95"], row["p99"], row["ci95_half"]])
            # Extra per-run quantities that exist in runs.jsonl but not in summary.csv.
            for (n, variant), recs in groups(e["records"]).items():
                for m in ("commands_committed", "commit_latency_ms_p95", "commit_latency_ms_p99"):
                    vals = [float(r[m]) for r in recs if r["status"] == "ok" and r.get(m) is not None]
                    s = summarize(vals)
                    if s is None:
                        w.writerow([e["id"], n, variant, m, "runs.jsonl", len(recs), 0] + [""] * 8)
                    else:
                        w.writerow([e["id"], n, variant, m, "runs.jsonl", len(recs), s["n"], fmt(s["mean"], 8),
                                    fmt(s["std_dev"], 8), fmt(s["median"], 8), fmt(s["min"], 8), fmt(s["max"], 8),
                                    fmt(s["p95"], 8), fmt(s["p99"], 8), fmt(s["ci95_half"], 8)])

    with open(OUT / "workload-artifact-check.csv", "w", newline="", encoding="utf-8") as fh:
        w = csv.writer(fh)
        w.writerow(["experiment_id", "node_count", "fault_removal_ms", "last_command_ms", "runs_with_recovery",
                    "min_stable_minus_last_command_ms", "median_stable_minus_last_command_ms",
                    "max_stable_minus_last_command_ms", "median_recovery_time_ms"])
        for e in data.values():
            sc = e["scenario"]
            rem, end = removal_ms(sc), workload_end_ms(sc)
            if rem is None or end is None:
                continue
            for (n, _), recs in groups(e["records"]).items():
                rec = [r["recovery_time_ms"] for r in recs if r.get("recovery_time_ms") is not None]
                if not rec:
                    continue
                d = [rem + x - end for x in rec]
                w.writerow([e["id"], n, rem, end, len(rec), fmt(min(d), 6), fmt(statistics.median(d), 6),
                            fmt(max(d), 6), fmt(statistics.median(rec), 6)])


